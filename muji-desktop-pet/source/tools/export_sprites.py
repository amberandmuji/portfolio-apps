"""Regenerate Sources/Sprites.swift from tools/sprites.py (needs Python 3 + Pillow).
   python3 tools/export_sprites.py && ./build.sh"""
import base64, io, os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import sprites

F = sprites.frames()
out = ['// Generated by tools/export_sprites.py - do not edit by hand.',
       '// 48x32 pixel-art frames (PNG, base64), facing right. Paws on row 29, outline on row 30.',
       'import Foundation', '', 'enum SpriteData {',
       f'    static let width = {sprites.W}', f'    static let height = {sprites.H}',
       f'    static let groundRow = {sprites.GROUND}',
       '    static let frames: [String: [String]] = [']
for name, frames in F.items():
    out.append(f'        "{name}": [')
    for im in frames:
        b = io.BytesIO(); im.save(b, 'PNG', optimize=True)
        out.append(f'            "{base64.b64encode(b.getvalue()).decode()}",')
    out.append('        ],')
out += ['    ]', '}', '']
dst = os.path.join(here, '..', 'Sources', 'Sprites.swift')
open(dst, 'w').write('\n'.join(out))
print('wrote', os.path.normpath(dst))
